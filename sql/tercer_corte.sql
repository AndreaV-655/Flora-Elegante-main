CREATE TABLE IF NOT EXISTS fe_job (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 clave VARCHAR(190) NOT NULL UNIQUE,
 canal VARCHAR(20) NOT NULL,
 payload LONGTEXT NOT NULL,
 estado VARCHAR(20) NOT NULL DEFAULT 'pendiente',
 intentos INT NOT NULL DEFAULT 0,
 disponible DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 resultado VARCHAR(200) NULL,
 INDEX idx_fe_job (estado, disponible)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fe_audit (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 fecha DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 accion VARCHAR(80) NOT NULL,
 referencia VARCHAR(190) NOT NULL,
 resultado VARCHAR(200) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fe_state (
 clave VARCHAR(190) PRIMARY KEY,
 valor VARCHAR(190) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fe_cupon (
 codigo VARCHAR(40) PRIMARY KEY,
 cliente_id BIGINT NOT NULL,
 porcentaje INT NOT NULL,
 vence DATE NOT NULL,
 usado_pedido BIGINT NULL,
 clave VARCHAR(190) NOT NULL UNIQUE,
 FOREIGN KEY (cliente_id) REFERENCES usuario(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fe_vision (
 id CHAR(32) PRIMARY KEY,
