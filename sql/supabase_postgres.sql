create extension if not exists pgcrypto;

create table if not exists rol (
    id bigint generated by default as identity primary key,
    nombre varchar(30) not null unique
);

insert into rol (nombre) values ('cliente'), ('administrador'), ('empleado')
on conflict (nombre) do nothing;

create table if not exists usuario (
    id bigint generated by default as identity primary key,
    nombre varchar(120) not null,
    email varchar(160) not null unique,
    password_hash varchar(255) not null,
    rol_id bigint not null,
    activo smallint not null default 1 check (activo in (0, 1)),
    fecha_registro timestamptz not null default now(),
    ultimo_acceso timestamptz,
    constraint fk_usuario_rol foreign key (rol_id) references rol(id)
);

create index if not exists idx_usuario_rol on usuario (rol_id);

create table if not exists cliente_perfil (
    usuario_id bigint primary key,
    telefono varchar(30),
    direccion text,
    fecha_nacimiento date,
    preferencias_florales varchar(60),
    identificacion varchar(40),
    metodo_pago varchar(40),
    marketing smallint not null default 0 check (marketing in (0, 1)),
    actualizado_en timestamptz not null default now(),
    constraint fk_perfil_usuario foreign key (usuario_id) references usuario(id) on delete cascade
);

create or replace function fn_actualizar_actualizado_en()
returns trigger
language plpgsql
as $$
begin
    new.actualizado_en = now();
    return new;
end;
$$;

drop trigger if exists trg_cliente_perfil_actualizado on cliente_perfil;
create trigger trg_cliente_perfil_actualizado
before update on cliente_perfil
for each row execute function fn_actualizar_actualizado_en();

