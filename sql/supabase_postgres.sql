create table if not exists pedido (
    id bigint generated by default as identity primary key,
    cliente_id bigint not null,
    fecha timestamptz not null default now(),
    estado varchar(20) not null default 'Confirmado',
    total numeric(12,2) not null default 0,
    codigo varchar(40) unique,
    entrega timestamptz,
    fecha_evento timestamptz,
    dedicatoria varchar(500),
    ocasion varchar(40),
    descuento numeric(12,2) not null default 0,
    constraint fk_pedido_cliente foreign key (cliente_id) references usuario(id)
);

create index if not exists idx_pedido_cliente on pedido (cliente_id);

create table if not exists pedido_detalle (
    id bigint generated by default as identity primary key,
    pedido_id bigint not null,
    producto_id bigint not null,
    cantidad integer not null check (cantidad > 0),
    precio_unitario numeric(10,2) not null,
    costo_unitario numeric(10,2),
    constraint fk_detalle_pedido foreign key (pedido_id) references pedido(id) on delete cascade,
    constraint fk_detalle_producto foreign key (producto_id) references producto(id)
);

create table if not exists intento_login (
    id bigint generated by default as identity primary key,
    email varchar(150) not null,
    ip varchar(45) not null default '',
    exito smallint not null default 0 check (exito in (0, 1)),
    user_agent varchar(255),
    fecha timestamptz not null default now()
);

create index if not exists idx_intento_email on intento_login (email, fecha);
create index if not exists idx_intento_ip on intento_login (ip, fecha);

create table if not exists interaccion (
    id bigint generated by default as identity primary key,
    usuario_id bigint,
    canal varchar(20) not null default 'chatbot',
    fecha timestamptz not null default now(),
    calificacion smallint check (calificacion between 1 and 5),
    sugerencia text,
    constraint fk_interaccion_usuario foreign key (usuario_id) references usuario(id) on delete set null
);

create index if not exists idx_interaccion_fecha on interaccion (fecha);

create table if not exists fe_job (
    id bigint generated by default as identity primary key,
    clave varchar(190) not null unique,
    canal varchar(20) not null,
    payload text not null,
    estado varchar(20) not null default 'pendiente',
    intentos integer not null default 0,
    disponible timestamptz not null default now(),
    creado timestamptz not null default now(),
    resultado varchar(200)
);

create index if not exists idx_fe_job on fe_job (estado, disponible);

create table if not exists fe_audit (
    id bigint generated by default as identity primary key,
    fecha timestamptz not null default now(),
    accion varchar(80) not null,
    referencia varchar(190) not null,
    resultado varchar(200) not null
);

create table if not exists fe_state (
    clave varchar(190) primary key,
    valor varchar(190) not null
);

create table if not exists fe_cupon (
    codigo varchar(40) primary key,
    cliente_id bigint not null,
    porcentaje integer not null,
    vence date not null,
    usado_pedido bigint,
    clave varchar(190) not null unique,
    constraint fk_fe_cupon_cliente foreign key (cliente_id) references usuario(id)
);

create table if not exists fe_vision (
    id varchar(32) primary key,
    usuario_id bigint not null,
    creado timestamptz not null default now(),
    archivo varchar(100) not null,
    resultado text,
    estado varchar(20) not null default 'procesando',
